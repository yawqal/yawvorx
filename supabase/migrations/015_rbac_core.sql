-- YAWVOREX 015: RBAC Core Tables
-- Creates the foundational tables for the new multi-role RBAC system.

begin;

-- 1. Lookup Tables
create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  code text not null unique, -- customer, vendor, freelancer, admin
  name text not null
);

create table if not exists public.permissions (
  id bigint generated by default as identity primary key,
  code text not null unique, -- products:manage, roles:assign_admin, etc.
  description text
);

create table if not exists public.role_permissions (
  role_id bigint references public.roles(id) on delete cascade,
  permission_id bigint references public.permissions(id) on delete cascade,
  primary key (role_id, permission_id)
);

create table if not exists public.permission_scopes (
  id bigint generated by default as identity primary key,
  code text not null unique -- e.g., 'vendor_id', 'global'
);

-- 2. User/Role Mapping
create table if not exists public.user_roles_v2 (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  role_id bigint not null references public.roles(id) on delete cascade,
  status text not null default 'active' check (status in ('pending', 'active', 'rejected', 'suspended', 'revoked')),
  suspended_at timestamptz,
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (user_id, role_id)
);

create table if not exists public.user_role_scopes (
  user_role_id uuid references public.user_roles_v2(id) on delete cascade,
  scope_id bigint references public.permission_scopes(id) on delete cascade,
  scope_value uuid not null, -- The actual vendor_id, etc.
  primary key (user_role_id, scope_id, scope_value)
);

-- 3. Workflow & Status
create table if not exists public.role_applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  role_id bigint not null references public.roles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  admin_note text,
  reviewed_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.account_status (
  user_id uuid primary key references auth.users(id) on delete cascade,
  status text not null default 'active' check (status in ('active', 'suspended')),
  reason text,
  updated_at timestamptz not null default now()
);

-- 4. Audit Log
create table if not exists public.security_audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id),
  action text not null,
  target_table text,
  target_id uuid,
  old_val jsonb,
  new_val jsonb,
  created_at timestamptz not null default now()
);

-- RLS Enforcement
alter table public.roles             enable row level security;
alter table public.permissions       enable row level security;
alter table public.role_permissions  enable row level security;
alter table public.user_roles_v2     enable row level security;
alter table public.account_status    enable row level security;
alter table public.security_audit_logs enable row level security;

-- Audit Log Immutable Policy
revoke all on public.security_audit_logs from authenticated, anon;
grant select on public.security_audit_logs to authenticated; -- Admins only (via RLS)

commit;
